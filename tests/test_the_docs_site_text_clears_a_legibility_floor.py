# Our override                                                                #
# --------------------------------------------------------------------------- #


def test_inline_code_declares_a_floor() -> None:
    """`palette.css` must floor inline code at the legibility floor."""
    css = _palette()
    match = re.search(
        r"\.md-typeset\s+code\s*\{[^}]*?font-size:\s*max\(\s*([0-9.]+)em\s*,\s*"
        r"([0-9.]+)px\s*\)",
        css,
        re.DOTALL,
    )
    assert match is not None, (
        "docs/assets/css/palette.css no longer floors `.md-typeset code` with a "
        "`max(<n>em, <n>px)` font-size. Inline code inside a table or an admonition "
        "falls to 10.88px without it."
    )
    relative, floor = float(match.group(1)), float(match.group(2))
    assert floor >= _FLOOR_PX, (
        f"the inline-code floor is {floor}px, under the {_FLOOR_PX}px legibility floor"
    )
    # `max()` is what keeps the override from *shrinking* anything: prose code stays at
    # the theme's own .85em (13.6px) and only the sub-floor cases move. A plain `px`
    # font-size here would flatten that distinction, which is a design change rather
    # than an accessibility fix.
    assert 0 < relative <= 1, (
        f"the relative term is {relative}em; the override is meant to preserve the "
        "theme's reduction of code against its container, not replace it"
    )


def _scheme_block(css: str, selector: str) -> str:
    """Return the body of the rule whose selector list contains `selector`."""
    for sel, body in re.findall(r"([^{}]+)\{([^{}]*)\}", css):
        if selector in sel:
            return body
    raise AssertionError(f"palette.css declares no block for {selector}")


def _declared(block: str, name: str) -> str | None:
    match = re.search(rf"{re.escape(name)}:\s*(#[0-9a-fA-F]{{6}})\b", block)
    return match.group(1) if match else None


def test_the_light_scheme_contrast_clears_wcag_aa() -> None:
    """White on the light-scheme primary and accent must clear 4.5:1.

    This is precisely the pairing that failed: the theme puts white text on the primary
    ground for the header, the buttons and the active navigation item, and the stock
    `teal` primary #009688 gives 3.67:1. Until now nothing re-measured it, so an edit
    to any of these hexes would have been silent.
    """
    block = _scheme_block(_palette(), '[data-md-color-scheme="default"]')
    for name in ("--md-primary-fg-color", "--md-accent-fg-color"):
        ground = _declared(block, name)
        assert ground is not None, f"the light scheme sets no {name}"
        ratio = _contrast(ground, "#ffffff")
        assert ratio >= 4.5, (
            f"white on {name} {ground} is {ratio:.2f}:1, under the 4.5:1 WCAG AA "
            "minimum for body-sized text"
        )


def test_the_dark_scheme_accent_is_lighter_than_the_light_scheme_one() -> None:
    """The two accents must sit on opposite sides, because their grounds do.

    `palette.css` reasons that the dark scheme needs a *lighter* accent for the same
    reason the light one needs a darker one. The failure this catches is the easy one:
    copying one scheme's accent into the other block, which looks tidy and silently
    puts a dark link on a dark ground.
    """
    css = _palette()
    light = _declared(
        _scheme_block(css, '[data-md-color-scheme="default"]'), "--md-accent-fg-color"
    )
    dark = _declared(_scheme_block(css, '[data-md-color-scheme="slate"]'), "--md-accent-fg-color")
    assert light is not None and dark is not None
    assert _relative_luminance(dark) > _relative_luminance(light), (
        f"the slate accent {dark} is not lighter than the light-scheme accent "
        f"{light}; a dark accent on a dark ground is the failure this guards"
    )


def _relative_luminance(colour: str) -> float:
    """Return the WCAG relative luminance of a `#rrggbb` colour."""
    r, g, b = (int(colour[i : i + 2], 16) / 255 for i in (1, 3, 5))

    def channel(c: float) -> float:
        return c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4

    r, g, b = channel(r), channel(g), channel(b)
    return 0.2126 * r + 0.7152 * g + 0.0722 * b


def _contrast(a: str, b: str) -> float:
    """Return the WCAG contrast ratio between two `#rrggbb` colours."""
    la, lb = _relative_luminance(a), _relative_luminance(b)
    lighter, darker = max(la, lb), min(la, lb)
    return (lighter + 0.05) / (darker + 0.05)


def test_the_luminance_formula_matches_the_published_examples() -> None:
    """Pin the contrast maths itself against values published by the W3C.

    A guard that measures with the same arithmetic as the thing it guards cannot see an
    error in the arithmetic. These three are from the WCAG definition and are
    independent of anything in this repository.
    """
    assert _contrast("#000000", "#ffffff") == pytest.approx(21.0, abs=0.01)
    assert _contrast("#ffffff", "#ffffff") == pytest.approx(1.0, abs=0.01)
    # The stock mkdocs-material teal that failed, which is why palette.css exists.
    assert _contrast("#009688", "#ffffff") == pytest.approx(3.67, abs=0.01)


