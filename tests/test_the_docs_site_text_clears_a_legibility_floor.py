def _theme_assets() -> Path:
    """Return the installed mkdocs-material stylesheet directory, or skip."""
    material = pytest.importorskip(
        "material",
        reason="mkdocs-material is only installed with the `docs` extra",
    )
    return Path(material.__file__).parent / "templates" / "assets" / "stylesheets"


def _theme_sheet(prefix: str) -> str:
    assets = _theme_assets()
    sheets = sorted(assets.glob(f"{prefix}.*.min.css"))
    if not sheets:
        pytest.skip(f"no bundled {prefix} stylesheet under {assets}")
    return sheets[-1].read_text()


def _theme_stylesheet() -> str:
    """Return the installed mkdocs-material bundled main stylesheet, or skip."""
    return _theme_sheet("main")


def _hsl_to_hex(hue: float, sat: float, light: float) -> str:
    """Convert an HSL triple (degrees, 0-1, 0-1) to `#rrggbb`."""
    chroma = (1 - abs(2 * light - 1)) * sat
    sector = (hue % 360) / 60
    second = chroma * (1 - abs(sector % 2 - 1))
    table = [
        (chroma, second, 0.0),
        (second, chroma, 0.0),
        (0.0, chroma, second),
        (0.0, second, chroma),
        (second, 0.0, chroma),
        (chroma, 0.0, second),
    ]
    r, g, b = table[int(sector) % 6]
    offset = light - chroma / 2
    return "#" + "".join(f"{round((c + offset) * 255):02x}" for c in (r, g, b))


def test_the_dark_scheme_accent_clears_wcag_aa_on_the_theme_ground() -> None:
    """The slate accent must clear 4.5:1 against the ground the theme actually paints.

    The ground is resolved from the installed theme rather than written down here, so
    a theme that darkens or lightens slate re-measures this pairing instead of leaving
    a stale ratio in a comment.
    """
    # The hue default lives in the main sheet (as `225deg`); the slate scheme's
    # background, which reads it, lives in the palette sheet.
    hue_match = re.search(r"--md-hue:\s*([0-9.]+)deg?", _theme_sheet("main"))
    assert hue_match is not None, "the theme no longer defines a default --md-hue"
    palette_css = _theme_sheet("palette")
    slate = _scheme_block(palette_css, "[data-md-color-scheme=slate]")
    bg = re.search(
        r"--md-default-bg-color:\s*hsla\(var\(--md-hue\),\s*([0-9.]+)%,\s*([0-9.]+)%",
        slate,
    )
    assert bg is not None, (
        "the theme's slate --md-default-bg-color is no longer an hsla() of --md-hue; "
        "re-derive the dark-scheme ground"
    )
    ground = _hsl_to_hex(
        float(hue_match.group(1)), float(bg.group(1)) / 100, float(bg.group(2)) / 100
    )
    accent = _declared(
        _scheme_block(_palette(), '[data-md-color-scheme="slate"]'),
        "--md-accent-fg-color",
    )
    assert accent is not None, "the slate scheme sets no --md-accent-fg-color"
    ratio = _contrast(accent, ground)
    assert ratio >= 4.5, (
        f"the slate accent {accent} on the theme's slate ground {ground} is "
        f"{ratio:.2f}:1, under the 4.5:1 WCAG AA minimum"
    )


def test_the_hsl_conversion_matches_known_values() -> None:
    """Pin the HSL maths against values that do not come from this repository."""
    assert _hsl_to_hex(0, 1.0, 0.5) == "#ff0000"
    assert _hsl_to_hex(120, 1.0, 0.5) == "#00ff00"
    assert _hsl_to_hex(240, 1.0, 0.5) == "#0000ff"
    assert _hsl_to_hex(0, 0.0, 0.0) == "#000000"
    assert _hsl_to_hex(0, 0.0, 1.0) == "#ffffff"
    assert _hsl_to_hex(210, 0.5, 0.5) == "#4080bf"


def test_the_theme_still_needs_the_floor() -> None:
    """The theme's own numbers must still produce sub-floor inline code.

    This is the two-sided half of the guard. It fails if `mkdocs-material` moves any of
    the three numbers the override reasons about — and a failure is not necessarily a
    regression: if the theme raises its own sizes, the override has become redundant and
    should be removed rather than kept as decoration.
    """
    css = _theme_stylesheet()

    # 1. The root scale. Every px figure in palette.css's comment is computed from it,
    #    and the memory of this finding was once written down against a 16px root,
    #    which made every number in it wrong by 25%.
    roots = {float(m) for m in re.findall(r"html\{font-size:([0-9.]+)%", css)}
    assert 125.0 in roots, (
        f"mkdocs-material no longer sets a 125% base root font-size (found {roots}); "
        "re-derive the pixel figures in docs/assets/css/palette.css"
    )
    root_px = 16.0 * 1.25

    # 2. Inline code is still a relative reduction.
    code = re.search(r"\.md-typeset code\{[^}]*?font-size:([0-9.]+)em", css)
    assert code is not None, (
        "mkdocs-material no longer sizes `.md-typeset code` in `em`; the compounding "
        "the override corrects may no longer happen"
    )
    code_factor = float(code.group(1))

    # 3. The smallest container that can hold inline code. Tables and admonitions are
    #    both in the `.64rem` family; take the smallest rem size the theme applies to a
    #    typeset container rather than hard-coding one, so a new reduced context is
    #    caught too.
    containers = [
        float(m)
        for sel, m in re.findall(r"([^{}]*)\{[^}]*?font-size:\s*([0-9.]+)rem", css, re.DOTALL)
        if ".md-typeset" in sel and "code" not in sel and "pre" not in sel
    ]
    assert containers, "found no .md-typeset container font sizes in the theme"
    smallest_px = min(containers) * root_px

    rendered = smallest_px * code_factor
    assert rendered < _FLOOR_PX, (
        f"inline code in the theme's smallest typeset container now renders at "
        f"{rendered:.2f}px, at or above the {_FLOOR_PX}px floor. The override in "
        "docs/assets/css/palette.css is redundant — remove it rather than keep it."
    )


def test_the_floor_does_not_fire_at_the_wide_breakpoint() -> None:
    """At the `>=100em` breakpoint the theme is already above the floor.

    The case where a clamp must *not* fire. A floor that fires everywhere is
    indistinguishable from simply setting the size, and would be flattening a
    distinction the theme makes on purpose.
    """
    css = _theme_stylesheet()
    wide = re.search(r"@media screen and \(min-width:100em\)\{html\{font-size:([0-9.]+)%", css)
    assert wide is not None, "the >=100em root scaling breakpoint is gone from the theme"
    root_px = 16.0 * float(wide.group(1)) / 100.0

    code = re.search(r"\.md-typeset code\{[^}]*?font-size:([0-9.]+)em", css)
    assert code is not None
    code_factor = float(code.group(1))

    containers = [
        float(m)
        for sel, m in re.findall(r"([^{}]*)\{[^}]*?font-size:\s*([0-9.]+)rem", css, re.DOTALL)
        if ".md-typeset" in sel and "code" not in sel and "pre" not in sel
    ]
    rendered = min(containers) * root_px * code_factor
    assert rendered >= _FLOOR_PX, (
        f"at the wide breakpoint inline code renders at {rendered:.2f}px, under the "
        f"{_FLOOR_PX}px floor. The override's comment claims the floor does not fire "
        "here; re-measure and correct it."
    )
