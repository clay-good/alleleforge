"""The docs site rendered 3,937 pieces of text below an 11px legibility floor.

Every one of them was inline ``code``, and on an API reference that is the identifiers
— the most load-bearing words on the page.

The cause is a *relative* unit compounding. The theme sizes ``.md-typeset code`` at
``.85em``, which is right in running prose: the container is 16px and code lands at
13.6px. But inside a table or an admonition the theme has already reduced the container
to ``.64rem`` — 12.8px at its 125% root — and .85 of that is 10.88px. Neither rule is
wrong on its own. The product is, and this repository authors neither one.

Nothing was going to notice, for three reasons that are worth keeping written down:

* ``site/`` is gitignored build output, so the only artifact that exhibits the problem
  is regenerated by every build and committed by nothing.
* ``mkdocs build --strict`` is a CI gate, but strictness there is about broken links and
  missing references, not about what the rendered page measures.
* the sizes are not in any file this project owns. Reading ``palette.css`` — the one
  stylesheet here — shows colors and now a floor, and tells you nothing about the
  theme's own numbers.

So the finding was only ever available by measuring the built pages in a browser, which
no gate does. What *can* be pinned cheaply is the pair of facts the fix rests on, and
that is what this module does. ``test_inline_code_declares_a_floor`` guards our
override; ``test_the_theme_still_needs_the_floor`` guards the assumption underneath it,
because ``mkdocs-material`` is depended on as ``>=9.5`` and an upgrade is free to move
any of these numbers — including to fix the problem itself, which would make the
override redundant rather than wrong.

The second test is also the case where the floor must *not* fire: at the ``>=100em``
breakpoint the root grows to 137.5% and table code already computes to 11.97px, so
``max()`` leaves it alone. A floor with no such case is a floor nobody has measured.

This module also closes a gap of its own: the WCAG contrast override in ``palette.css``
had been load-bearing since it was added and was guarded by nothing at all.
"""

from __future__ import annotations

import re
from pathlib import Path

import pytest

_ROOT = Path(__file__).resolve().parents[1]
_PALETTE = _ROOT / "docs" / "assets" / "css" / "palette.css"

#: The floor, in CSS pixels. Functional text at or above this is legible; below it is
#: not. Non-interactive legal smallprint may sit lower, and the site has none.
_FLOOR_PX = 11.0


def _palette() -> str:
    return _PALETTE.read_text()


