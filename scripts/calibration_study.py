#!/usr/bin/env python
"""Calibration study: regenerate the CRISPR-Bench calibration report (R5).

Two regenerable, deterministic-from-seed outputs:

1. **Per-task calibration table** — every CRISPR-Bench task's primary metric and
   its **ECE** (the honesty metric required on every task), measured against the
   reference baseline on the frozen splits.
2. **Conformal interval-recalibration demonstration** — on a deliberately
   miscalibrated regression set, the empirical interval coverage *before* and
   *after* :class:`~alleleforge.scoring.uncertainty.ConformalCalibrator` at the
   spec's interval levels, showing the split-conformal guarantee restore coverage
   to its nominal target.

On real weights (R1) the per-task numbers become the published reproduction; the
machinery and the report regenerate identically here on the weight-free splits.

Usage:
    python scripts/calibration_study.py            # print the markdown report
    python scripts/calibration_study.py --out PATH  # also write it to PATH
"""

from __future__ import annotations

import argparse
from pathlib import Path
from typing import Any

# The deterministic computations live in the library so the markdown report (here)
# and the SVG figures (alleleforge.viz) share one source of truth.
from alleleforge.benchmark.calibration import (
    LEVELS,
    conformal_demo,
    generalization_table,
    task_calibration_table,
)
from alleleforge.benchmark.tasks import TASKS
from alleleforge.config import get_settings

__all__ = [
    "LEVELS",
    "TASKS",
    "conformal_demo",
    "generalization_table",
    "main",
    "render_markdown",
    "task_calibration_table",
]


def _cell(value: Any) -> str:
    """Render one table value: the number, or the word for its absence.

    A metric can be undefined — a correlation over constant predictions, calibration
    with no scorable pair — and `None` is what the table row carries. Printing that
    repr in a column of numbers says nothing a reader can act on, in the document this
    project offers as its calibration evidence.
    """
    return "undefined" if value is None else str(value)


def _provenance(row: dict[str, Any]) -> str:
    """Return the corpus label for ``row``.

    The generalization rows have carried a ``synthetic`` flag all along and the table
    never printed it, so a generalization gap -- the claim most easily mistaken for a
    measurement of a model -- was the one section a reader could not read a corpus off.
    """
    return "synthetic" if row["synthetic"] else "real"


def render_markdown(
    tasks: list[dict[str, Any]], generalization: list[dict[str, Any]], demo: list[dict[str, Any]]
) -> str:
    """Render the calibration report as markdown."""
    lines = [
        "# CRISPR-Bench calibration report",
        "",
        "Regenerated by `scripts/calibration_study.py` from config + seed.",
        "",
    ]
    # The report is the artifact a reader treats as the project's calibration evidence,
    # and every number in it comes from the bundled synthetic stand-ins shipped so the
    # harness runs without the real corpora. Saying so once, in prose, at the top —
    # before any table — is the difference between a demonstration and a claim.
    stand_ins = sorted(str(r["task"]) for r in tasks if r["synthetic"])
    if stand_ins and len(stand_ins) == len(tasks):
        lines += [
            "> **Every number below is computed on the bundled SYNTHETIC stand-in",
            "> datasets**, shipped so the harness runs in CI without the real corpora,",
            "> at the sample sizes shown in the `n` column (single digits). They",
            "> demonstrate that the measurement machinery works end to end. They are",
            "> not measurements of any model, and must not be cited as such.",
            "",
        ]
    elif stand_ins:
        # The banner used to be all-or-nothing. One real corpus deleted it, warning and
        # all, from a table whose other rows were still stand-ins -- and corpora arrive
        # one task at a time, so that mixed table is the first one a reader will see.
        lines += [
            f"> **{len(stand_ins)} of {len(tasks)} rows below are computed on bundled",
            "> SYNTHETIC stand-in datasets** at single-digit `n`: "
            + ", ".join(f"`{name}`" for name in stand_ins)
            + ".",
            "> Those rows demonstrate the measurement machinery, not a model, and must",
            "> not be cited as measurements. The `Data` column marks every row.",
            "",
        ]
    lines += [
        "## Per-task calibration (baseline, frozen splits)",
        "",
        "| Task | Kind | Primary | Value | ECE | n | Data |",
        "|---|---|---|---:|---:|---:|---|",
    ]
    for r in tasks:
        # An absent value prints as the word, not as a bare `None` in a column of
        # numbers. This is the artifact a reader treats as the project's calibration
        # evidence; a Python repr in a value cell reads as a bug, and a reader who
        # decides it is one has learned nothing about why there is no number.
        lines.append(
            f"| {r['task']} | {r['kind']} | {r['primary_metric']} | "
            f"{_cell(r['primary_value'])} | {_cell(r['ece'])} | {r['n_test']} | "
            f"{_provenance(r)} |"
        )
    unmeasured = [r for r in tasks if r["primary_value"] is None]
    if unmeasured:
        lines.append("")
        for r in unmeasured:
            lines.append(
                f"- **{r['task']}: no {r['primary_metric']}.** {r['primary_undefined_reason']}"
            )
    lines += [
        "",
        "## Cross-cell-type generalization gap",
        "",
        "Primary metric on an in-context fold (a training-seen cell type) vs the",
        "held-out cell type. A positive gap means the model generalizes *worse* to",
        "the unseen context — a field-wide reality, reported, not hidden.",
        "",
        "| Task | Metric | In-context | Held-out | Gap | Held-out context | Data |",
        "|---|---|---:|---:|---:|---|---|",
    ]
    for r in generalization:
        # A gap can be absent: the baseline predicts one constant, so its rank
        # correlation is undefined on both folds and there is nothing to subtract. The
        # table says so and names the reason rather than printing `+0.0`.
        if r["gap"] is None:
            lines.append(
                f"| {r['task']} | {r['metric']} | — | — | undefined | "
                f"{r['held_out_context']} | {_provenance(r)} |"
            )
            continue
        lines.append(
            f"| {r['task']} | {r['metric']} | {r['in_context']} | "
            f"{r['held_out']} | {r['gap']:+} | {r['held_out_context']} | {_provenance(r)} |"
        )
    undefined = [r for r in generalization if r["gap"] is None]
    if undefined:
        lines.append("")
        for r in undefined:
            lines.append(f"- **{r['task']}: no gap.** {r['undefined_reason']}")
    lines += [
        "",
        "## Conformal interval recalibration",
        "",
        "Empirical coverage of a deliberately under-covering interval set, before and",
        "after split-conformal recalibration (synthetic, seeded). Recalibrated coverage",
        "meets the nominal level — the finite-sample guarantee.",
        "",
        "| Target level | Raw coverage | Recalibrated coverage | Width scale |",
        "|---:|---:|---:|---:|",
    ]
    for r in demo:
        lines.append(
            f"| {r['level']:.2f} | {r['raw_coverage']} | "
            f"{r['recalibrated_coverage']} | {r['scale']} |"
        )
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    """Regenerate and print (optionally write) the calibration report."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, default=None, help="also write the report to this path")
    args = parser.parse_args(argv)

    report = render_markdown(
        task_calibration_table(), generalization_table(), conformal_demo(get_settings().rng())
    )
    if args.out is not None:
        args.out.write_text(report)
        print(f"wrote {args.out}")
    print(report)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
